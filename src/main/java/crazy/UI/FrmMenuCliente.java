    private void btnQuitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarActionPerformed
        int fila = tablaPedido.getSelectedRow();
    
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto de la tabla");
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tablaPedido.getModel();
        modelo.removeRow(fila);

        //Volvemos a calcuar total
        double total = 0;
        for (int i = 0; i < modelo.getRowCount(); i++) {
            Object valor = modelo.getValueAt(i, 3);
        if (valor != null && !valor.toString().trim().equals("")) {
            total = total + Double.parseDouble(valor.toString());
        }
        }
        lblTotal.setText("TOTAL: Q" + String.format("%.2f", total));
    }//GEN-LAST:event_btnQuitarActionPerformed

    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        DefaultTableModel modelo = (DefaultTableModel) tablaPedido.getModel();
    if (modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "No hay productos");
        return;
    }

    try {
        PedidoDAO dao = new PedidoDAO();
        String numero = dao.generarNumeroTicket();

        String fecha = java.time.LocalDateTime.now().format(
            java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy HH:mm"));

        Pedido pedido = new Pedido();
        pedido.setNumeroTicket(numero);
        pedido.setFechaHora(java.time.LocalDateTime.now());

        StringBuilder texto = new StringBuilder();
        double total = 0;

        for (int i = 0; i < modelo.getRowCount(); i++) {
            int idProd = Integer.parseInt(modelo.getValueAt(i, 0).toString());
            String nombre = modelo.getValueAt(i, 1).toString();
            int cant = Integer.parseInt(modelo.getValueAt(i, 2).toString());
            double precio = Double.parseDouble(modelo.getValueAt(i, 3).toString());
            double sub = Double.parseDouble(modelo.getValueAt(i, 4).toString());

            texto.append(nombre).append("  x").append(cant).append("   Q").append(sub).append("\n");
            total += sub;

            DetallePedido det = new DetallePedido();
            Producto prod = new Producto();
            prod.setIdProducto(idProd);
            det.setProducto(prod);
            det.setCantidad(cant);
            det.setPrecioUnitario(precio);
            det.setSubtotal(sub);
            pedido.agregarDetalle(det);
        }

        pedido.setTotal(total);
        dao.guardarPedido(pedido);

        String ruta = System.getProperty("user.home") + "/Downloads/Ticket_" + numero + ".pdf";
        TicketPDF.generar(numero, fecha, texto.toString(), total, ruta);
        java.awt.Desktop.getDesktop().open(new java.io.File(ruta));

        modelo.setRowCount(0);
        lblTotal.setText("TOTAL: Q0.00");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnConfirmarActionPerformed

