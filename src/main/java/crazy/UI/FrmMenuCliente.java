    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        if (listaProductos.getSelectedIndex() == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un producto");
        return;
    }

    try {
        String texto = listaProductos.getSelectedValue().toString();
        String[] partes = texto.split(" - Q");
        String nombre = partes[0];
        double precio = Double.parseDouble(partes[1]);

        // Buscar el id del producto
        int idProducto = 0;
        ProductoDAO dao = new ProductoDAO();
        List<Producto> lista = dao.listar();
        for (Producto p : lista) {
            if (p.getNombre().equals(nombre)) {
                idProducto = p.getIdProducto();
                break;
            }
        }

        String cantid = JOptionPane.showInputDialog(this, "Cantidad:");
        if (cantid == null || cantid.equals("")) {
            return;
        }

        int cantidad = Integer.parseInt(cantid);
        double subtotal = precio * cantidad;

        DefaultTableModel modelo = (DefaultTableModel) tablaPedido.getModel();
        modelo.addRow(new Object[]{idProducto, nombre, cantidad, precio, subtotal});

        double total = 0;
        for (int i = 0; i < modelo.getRowCount(); i++) {
            Object valor = modelo.getValueAt(i, 4);
            if (valor != null && !valor.toString().trim().equals("")) {
                total += Double.parseDouble(valor.toString());
            }
        }
        lblTotal.setText("TOTAL: Q" + String.format("%.2f", total));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
       
    }//GEN-LAST:event_btnAgregarActionPerformed

