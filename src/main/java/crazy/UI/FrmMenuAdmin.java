    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtNombre.getText().trim().isEmpty() || txtPrecio.getText().trim().isEmpty()) {
              JOptionPane.showMessageDialog(this, "Debe completar los campos de Nombre y Precio");
               return;
            }
            double precio = Double.parseDouble(txtPrecio.getText().trim());
            if (precio <= 0) {
                JOptionPane.showMessageDialog(this, "El precio debe ser mayor a 0");
                return;
            }
            
            Producto prod = new Producto();
            prod.setNombre(txtNombre.getText().trim());
            prod.setDescripcion(txtDescripcion.getText().trim());
            prod.setPrecio(precio);
            prod.setCategoria(cmbCategoria.getSelectedItem().toString());
            prod.setDisponible(chkDisponible.isSelected());

            ProductoDAO dao = new ProductoDAO();
            dao.insertar(prod);

            JOptionPane.showMessageDialog(this, "El producto fue guardado correctamente");
            listarProductos();
            limpiarCampos();

        } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El precio debe ser un numero");
        } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Ha ocurrido un error al guardar: ");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tablaProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaProductosMouseClicked
        int fila = tablaProductos.getSelectedRow();
    
        if (fila >= 0) {
        txtNombre.setText(tablaProductos.getValueAt(fila, 1).toString());
        txtDescripcion.setText(tablaProductos.getValueAt(fila, 2).toString());
        txtPrecio.setText(tablaProductos.getValueAt(fila, 3).toString());
        cmbCategoria.setSelectedItem(tablaProductos.getValueAt(fila, 4).toString());
        String disponible = tablaProductos.getValueAt(fila, 5).toString();
        chkDisponible.setSelected(disponible.equals("Sí"));
        }
    }//GEN-LAST:event_tablaProductosMouseClicked

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        try {
            int fila = tablaProductos.getSelectedRow();
        
            if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un producto de la tabla");
            return;
            }

            int id = Integer.parseInt(tablaProductos.getValueAt(fila, 0).toString());

            Producto prod = new Producto();
            prod.setIdProducto(id);
            prod.setNombre(txtNombre.getText().trim());
            prod.setDescripcion(txtDescripcion.getText().trim());
            prod.setPrecio(Double.parseDouble(txtPrecio.getText().trim()));
            prod.setCategoria(cmbCategoria.getSelectedItem().toString());
            prod.setDisponible(chkDisponible.isSelected());

            ProductoDAO dao = new ProductoDAO();
            dao.actualizar(prod);

            JOptionPane.showMessageDialog(this, "El producto se actualizó correctamente");
            listarProductos();
            limpiarCampos();
        
            } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar "+ e.getMessage());
            }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        try{
            int fila = tablaProductos.getSelectedRow();
        
            if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Porfavor seleccione un producto de la tabla");
            return;
            }

            int confirmar = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este producto?", "Confirmación de eliminación", JOptionPane.YES_NO_OPTION);

            if (confirmar == JOptionPane.YES_OPTION) {
                int id = Integer.parseInt(tablaProductos.getValueAt(fila, 0).toString());

                ProductoDAO dao = new ProductoDAO();
                dao.eliminar(id);

                JOptionPane.showMessageDialog(this, "El producto se eliminó correctamente");
                listarProductos();
                limpiarCampos();
            }
        
        } catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al eliminar"+ e.getMessage());
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

