    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String usuario = txtUsuario.getText().trim();
        String clave = new String(txtClave.getPassword()).trim();
        
        if (usuario.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Porfavor ingrese sus credenciales");
            return;
        }
        
        try {
            UsuarioDAO dao = new UsuarioDAO();
            Usuario user = dao.validacionLogin(usuario, clave);

            if (user != null) {
                // Primer caso correcto
                JOptionPane.showMessageDialog(this, "Bienvenido " + user.getNombre());
            
                FrmMenuAdmin admin = new FrmMenuAdmin();
                admin.setVisible(true);
                this.dispose();  // cerramos login
            } else {
                JOptionPane.showMessageDialog(this, "usuario o contraseña incorrectos");
                txtClave.setText("");
                txtUsuario.requestFocus();
            }
        
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Ha ocurrido un error al inciar sesion ");
        }
        
        
    }//GEN-LAST:event_btnIngresarActionPerformed

